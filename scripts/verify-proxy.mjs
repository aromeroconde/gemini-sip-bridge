import assert from 'node:assert/strict';
import http from 'node:http';
import { createRequire } from 'node:module';
import { once } from 'node:events';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { GoogleGenAI } from '@google/genai';
import * as google from '@livekit/agents-plugin-google';
import { sipProxyOptions } from '../dist/lib/proxy-config.js';
const require = createRequire(path.resolve(process.env.API_PROXY_SOURCE || '../api-proxy', 'package.json'));
const express = require('express'), WebSocket = require('ws');
const { authMiddleware } = require('./dist/middleware/auth');
const { registerAyniLive, ayniIsolation } = require('./dist/routes/ayni');
const { createSipRouter } = require('./dist/routes/sip');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sip-proxy-'));
process.env.TOKEN_GEMINI_SIP = 'synthetic-sip-token';
process.env.TOKEN_AYNI = 'synthetic-ayni-token';
process.env.USAGE_LEDGER_PATH = path.join(dir, 'usage.jsonl');
assert.throws(() => sipProxyOptions({ GOOGLE_API_KEY: 'legacy-must-not-work' }));
assert.throws(() => sipProxyOptions({ SIP_PROXY_URL: 'http://example.com', SIP_PROXY_TOKEN: 'x' }));
const providerServer = http.createServer(), provider = new WebSocket.WebSocketServer({ server: providerServer });
const calls = [];
provider.on('connection', ws => ws.on('message', raw => {
  const data = JSON.parse(raw); calls.push(data);
  if (data.setup) ws.send(JSON.stringify({ setupComplete: {} }));
  else ws.send(JSON.stringify({ serverContent: { turnComplete: true, modelTurn: { parts: [{ inlineData: { mimeType: 'audio/pcm;rate=24000', data: 'AAAA' } }] } }, usageMetadata: { totalTokenCount: 12 } }));
}));
await new Promise(r => providerServer.listen(0, '127.0.0.1', r));
const app = express(); app.use(express.json()); app.use('/proxy', authMiddleware, ayniIsolation);
app.use('/proxy/gemini-sip', createSipRouter({ key: () => 'synthetic-provider-only', request: async (url, options) => {
  assert.equal(options.headers['x-goog-api-key'], 'synthetic-provider-only');
  assert.ok(url.includes('gemini-2.5-flash:generateContent'));
  const body = JSON.parse(options.body); assert.equal(body.contents[0].parts[0].text, 'private-synthetic-transcript');
  return new Response(JSON.stringify({ candidates: [{ content: { role: 'model', parts: [{ text: 'synthetic-ok' }] } }], usageMetadata: { totalTokenCount: 20 } }));
} }));
app.use('/proxy', (_req, res) => res.json({ ok: true }));
const server = http.createServer(app);
const relay = registerAyniLive(server, { key: () => 'synthetic-provider-only', connect: () => new WebSocket(`ws://127.0.0.1:${providerServer.address().port}`) });
await new Promise(r => server.listen(0, '127.0.0.1', r));
const base = `http://127.0.0.1:${server.address().port}`;
const options = sipProxyOptions({ SIP_PROXY_URL: base, SIP_PROXY_TOKEN: 'synthetic-sip-token' });
const model = new google.beta.realtime.RealtimeModel({ model: 'gemini-3.8-live', ...options, apiVersion: 'v1beta' });
assert.equal(model._options.httpOptions.baseUrl, base + '/proxy/gemini-sip');
assert.equal(model._options.apiKey, 'proxy');
let session;
try {
  for (const route of ['/proxy/ayni/weather', '/proxy/gemini/token', '/proxy/lexcobro/models/x']) assert.equal((await fetch(base + route, { headers: { 'x-proxy-token': 'synthetic-sip-token' } })).status, 403);
  assert.equal((await fetch(base + '/proxy/gemini-sip/v1beta/models/gemini-2.5-flash:generateContent', { method: 'POST', headers: { 'content-type': 'application/json', 'x-proxy-token': 'synthetic-ayni-token' }, body: '{}' })).status, 403);
  const ai = new GoogleGenAI(options);
  const rest = await ai.models.generateContent({ model: 'gemini-2.5-flash', contents: 'private-synthetic-transcript' });
  assert.equal(rest.text, 'synthetic-ok');
  let readyResolve, audioResolve;
  const ready = new Promise(r => readyResolve = r), audio = new Promise(r => audioResolve = r);
  session = await ai.live.connect({ model: 'gemini-3.8-live', config: { responseModalities: ['AUDIO'], maxOutputTokens: 8192 }, callbacks: { onmessage: e => { if(e.setupComplete) readyResolve(); if(e.serverContent?.modelTurn) audioResolve(e); } } });
  await Promise.race([ready, new Promise((_, reject) => setTimeout(() => reject(Error('setup timeout')), 10000).unref())]);
  session.sendRealtimeInput({ audio: { mimeType: 'audio/pcm;rate=16000', data: 'AAAA' } });
  const result = await Promise.race([audio, new Promise((_, reject) => setTimeout(() => reject(Error('audio timeout')), 10000).unref())]);
  assert.equal(result.serverContent.modelTurn.parts[0].inlineData.data, 'AAAA');
  assert.equal(calls[0].setup.generationConfig.maxOutputTokens, 8192);
  session.close(); session = undefined;
  await new Promise(r => setTimeout(r, 20));
  const entries = fs.readFileSync(process.env.USAGE_LEDGER_PATH, 'utf8');
  const records = entries.trim().split('\n').map(JSON.parse);
  assert.ok(records.some(e => e.app === 'gemini-sip' && e.credential === 'GEMINI_API_KEY_SIP' && e.usage?.totalTokenCount === 12));
  assert.ok(records.some(e => e.app === 'gemini-sip' && e.usage?.totalTokenCount === 20));
  for (const value of ['private-synthetic-transcript','synthetic-provider-only','synthetic-sip-token']) assert.ok(!entries.includes(value));
  console.log('PASS: SIP LiveKit configuration + real Google SDK REST/Live + authenticated proxy + simulated provider; isolation, audio, output cap and private ledger.');
} finally {
  session?.close(); await model.close();
  for (const ws of relay.clients) ws.terminate(); for (const ws of provider.clients) ws.terminate();
  relay.close(); provider.close(); server.closeAllConnections();
  await Promise.all([new Promise(r => server.close(r)), new Promise(r => providerServer.close(r))]);
  fs.rmSync(dir, { recursive: true, force: true });
}
